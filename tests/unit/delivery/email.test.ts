describe("wrapInHtmlTemplate", () => {
  it("includes subject in title, body in container, and has footer", () => {
    const result = wrapInHtmlTemplate("Test Subject", "<p>Body content</p>");

    // Subject in title tag
    expect(result).toContain("<title>Test Subject</title>");

    // Body in container
    expect(result).toContain('<div class="container">');
    expect(result).toContain("<p>Body content</p>");

    // Footer present
    expect(result).toContain("Generated by Coronagraph Intelligence Platform");
    expect(result).toContain('<div class="footer">');

    // Valid HTML structure
    expect(result).toContain("<!DOCTYPE html>");
    expect(result).toContain("</html>");
  });
});

// ---------------------------------------------------------------------------
// sendEmail tests
// ---------------------------------------------------------------------------

describe("sendEmail", () => {
  let fetchSpy: ReturnType<typeof spyOn>;

  beforeEach(() => {
    currentConfig = { ...defaultConfig };
    fetchSpy = spyOn(globalThis, "fetch").mockImplementation(() =>
      Promise.resolve(
        new Response(JSON.stringify({ id: "email-123" }), { status: 200 }),
      ),
    );
  });

  afterEach(() => {
    fetchSpy.mockRestore();
  });

  it("successful send returns success with id", async () => {
    const result = await sendEmail(
      "test@example.com",
      "Test Subject",
      "<p>Hello</p>",
    );

    expect(result.success).toBe(true);
    expect(result.id).toBe("email-123");
    expect(fetchSpy).toHaveBeenCalledTimes(1);

    const callArgs = fetchSpy.mock.calls[0];
    expect(callArgs[0]).toBe("https://api.resend.com/emails");
    const body = JSON.parse(callArgs[1]?.body as string);
    expect(body.to).toEqual(["test@example.com"]);
    expect(body.subject).toBe("Test Subject");
    expect(body.html).toBe("<p>Hello</p>");
  });

  it("returns error when no RESEND_API_KEY configured", async () => {
    currentConfig = {
      ...defaultConfig,
      RESEND_API_KEY: undefined as unknown as string,
    };

    const result = await sendEmail("to@test.com", "Subject", "<p>Hi</p>");

    expect(result.success).toBe(false);
    expect(result.error).toContain("RESEND_API_KEY");
    expect(fetchSpy).not.toHaveBeenCalled();
  });

  it("returns error on API error response", async () => {
    fetchSpy.mockImplementation(() =>
      Promise.resolve(
        new Response("Bad Request: invalid email", { status: 400 }),
      ),
    );

    const result = await sendEmail("bad-email", "Subject", "<p>Hi</p>");

    expect(result.success).toBe(false);
    expect(result.error).toContain("400");
  });
});

