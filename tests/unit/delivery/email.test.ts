// ---------------------------------------------------------------------------
// Tests for src/delivery/email.ts
// ---------------------------------------------------------------------------

import { describe, it, expect, mock, beforeEach, afterEach, spyOn } from "bun:test";

// ---------------------------------------------------------------------------
// Mocks -- must be declared before importing the module under test.
// We use a mutable config object so tests can override values without
// re-mocking the module (which leaks across test files in Bun).
// ---------------------------------------------------------------------------

const defaultConfig = {
  ANTHROPIC_API_KEY: "test-key",
  RESEND_API_KEY: "test-resend-key",
  EMAIL_TO: "test@example.com",
  TELEGRAM_BOT_TOKEN: "test-bot-token",
  TELEGRAM_CHAT_ID: "test-chat-id",
  EMBEDDING_API_KEY: "test-embedding-key",
  EMBEDDING_MODEL: "voyage-3",
  EMBEDDING_DIMENSIONS: 1024,
  DATABASE_URL: "postgresql://test:test@localhost:5432/test",
  PORT: 3000,
};

let currentConfig = { ...defaultConfig };

mock.module("../../../src/config.ts", () => ({
  getConfig: () => currentConfig,
}));

// Import AFTER mocks are set up
const {
  escapeHtml,
  markdownToHtml,
  wrapInHtmlTemplate,
  sendEmail,
  sendBriefEmail,
  sendAlertEmail,
} = await import("../../../src/delivery/email.ts");

type AlertEmailData = {
  itemTitle: string;
  urgency: string;
  reason: string;
  recommendedAction: string;
  url?: string | null;
};

// ---------------------------------------------------------------------------
// Pure function tests -- escapeHtml
// ---------------------------------------------------------------------------

describe("escapeHtml", () => {
  it("escapes &, <, >, and double quotes", () => {
    const input = 'Hello & "world" <script>alert(1)</script>';
    const result = escapeHtml(input);

    expect(result).toBe(
      "Hello &amp; &quot;world&quot; &lt;script&gt;alert(1)&lt;/script&gt;",
    );
  });

  it("handles empty string", () => {
    expect(escapeHtml("")).toBe("");
  });
});

// ---------------------------------------------------------------------------
// Pure function tests -- markdownToHtml
// ---------------------------------------------------------------------------

describe("markdownToHtml", () => {
  it("converts h1 headers", () => {
    const result = markdownToHtml("# Main Title");
    expect(result).toContain("<h1>Main Title</h1>");
  });

  it("converts h2 headers", () => {
    const result = markdownToHtml("## Section Title");
    expect(result).toContain("<h2>Section Title</h2>");
  });

  it("converts h3 headers", () => {
    const result = markdownToHtml("### Sub Section");
    expect(result).toContain("<h3>Sub Section</h3>");
  });

  it("converts bold and italic text", () => {
    const result = markdownToHtml("This is **bold** and *italic* text");
    expect(result).toContain("<strong>bold</strong>");
    expect(result).toContain("<em>italic</em>");
  });

  it("converts inline code", () => {
    const result = markdownToHtml("Use the `getConfig()` function");
    expect(result).toContain("<code>getConfig()</code>");
  });

  it("converts unordered lists", () => {
    const result = markdownToHtml("- Item one\n- Item two\n- Item three");
    expect(result).toContain("<ul>");
    expect(result).toContain("<li>Item one</li>");
    expect(result).toContain("<li>Item two</li>");
    expect(result).toContain("<li>Item three</li>");
    expect(result).toContain("</ul>");
  });

  it("converts links", () => {
    const result = markdownToHtml(
      "Visit [Example](https://example.com) for more",
    );
    expect(result).toContain('<a href="https://example.com">Example</a>');
  });
});

