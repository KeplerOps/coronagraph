// sendAlertEmail tests
// ---------------------------------------------------------------------------

describe("sendAlertEmail", () => {
  let fetchSpy: ReturnType<typeof spyOn>;

  beforeEach(() => {
    currentConfig = { ...defaultConfig };
    fetchSpy = spyOn(globalThis, "fetch").mockImplementation(() =>
      Promise.resolve(
        new Response(JSON.stringify({ id: "alert-email-789" }), {
          status: 200,
        }),
      ),
    );
  });

  afterEach(() => {
    fetchSpy.mockRestore();
  });

  it("formats multiple alerts with urgency colors", async () => {
    const alerts: AlertEmailData[] = [
      {
        itemTitle: "Critical RCE in Apache",
        urgency: "critical",
        reason: "Active exploitation detected",
        recommendedAction: "Patch immediately",
        url: "https://example.com/advisory/1",
      },
      {
        itemTitle: "High Severity XSS",
        urgency: "high",
        reason: "Public exploit available",
        recommendedAction: "Update to latest version",
        url: null,
      },
    ];

    const result = await sendAlertEmail(alerts);

    expect(result.success).toBe(true);
    expect(fetchSpy).toHaveBeenCalledTimes(1);

    const callArgs = fetchSpy.mock.calls[0];
    const body = JSON.parse(callArgs[1]?.body as string);

    // Subject should reference alert count and first urgency
    expect(body.subject).toContain("[ALERT]");
    expect(body.subject).toContain("2 items");
    expect(body.subject).toContain("CRITICAL");

    // HTML body should contain both alerts
    expect(body.html).toContain("Critical RCE in Apache");
    expect(body.html).toContain("High Severity XSS");

    // Critical alert should have red border color
    expect(body.html).toContain("#dc2626");
    // High alert should have orange border color
    expect(body.html).toContain("#ea580c");

    // URL should be present for the first alert
    expect(body.html).toContain("https://example.com/advisory/1");
    expect(body.html).toContain("View source");
  });

  it("returns error when no EMAIL_TO configured", async () => {
    currentConfig = {
      ...defaultConfig,
      EMAIL_TO: undefined as unknown as string,
    };

    const alerts: AlertEmailData[] = [
      {
        itemTitle: "Test Alert",
        urgency: "medium",
        reason: "Test reason",
        recommendedAction: "Test action",
      },
    ];

    const result = await sendAlertEmail(alerts);

    expect(result.success).toBe(false);
    expect(result.error).toContain("EMAIL_TO");
  });
});
